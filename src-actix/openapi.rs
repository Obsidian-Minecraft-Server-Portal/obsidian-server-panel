pub fn configure(cfg: &mut web::ServiceConfig) {
	let doc = document();
	cfg.service(Scalar::with_url(DOCS_PATH, doc.clone()))
		.app_data(web::Data::new(doc))
		.route(SPEC_PATH, web::get().to(spec));
}

fn document() -> utoipa::openapi::OpenApi {
	#[cfg_attr(not(feature = "updater"), allow(unused_mut))]
	let mut doc = ApiDoc::openapi();
	#[cfg(feature = "updater")]
	doc.merge(crate::updater::UpdaterApi::openapi());
	doc
}

async fn spec(doc: web::Data<utoipa::openapi::OpenApi>) -> HttpResponse {
	HttpResponse::Ok().json(doc.get_ref())
}
