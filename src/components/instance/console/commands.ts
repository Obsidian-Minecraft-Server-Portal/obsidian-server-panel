const MAX_SUGGESTIONS = 6;

export function suggestCommands(input: string): string[] {
  const text = input.trimStart();
  if (!text) return [];
  return COMMANDS.filter((command) => command.startsWith(text) && command !== text).slice(0, MAX_SUGGESTIONS);
}
